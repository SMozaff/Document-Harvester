//! Region selections expressed in the rendered page viewport.
//!
//! A drag is captured in physical screen pixels and converted once to canonical,
//! unrotated PDF user space through the same PageTransform used by the viewer.
//! The page-space rectangle is the authoritative stored form. Overlays are
//! re-projected from it on zoom, pan, rotation, and viewport (pane) resize, so
//! the stored geometry never depends on the viewport. Do not duplicate zoom,
//! pan, crop-box, or rotation arithmetic.

use dh_core::{DhError, Result};
use dh_ir::BBox;

use crate::view_transform::PageTransform;

/// One rectangular selection on a PDF page.
///
/// `rectangle` is the drag in physical viewport pixels with a top-left origin.
/// It is converted once, at capture time, to page user space; the page-space
/// rectangle is what the application stores.
#[derive(Debug, Clone, PartialEq)]
pub struct RegionSelection {
    pub page: u32,
    pub rectangle: BBox,
}

impl RegionSelection {
    /// Convert this screen-space selection into unrotated PDF page user space.
    ///
    /// The result is validated against the transform's effective page box.
    /// Rectangles touching the page boundary are valid; rectangles extending
    /// beyond it are rejected rather than clipped.
    pub fn to_page_user_space(&self, transform: &PageTransform) -> Result<BBox> {
        let page_rectangle = transform.screen_rect_to_page(self.rectangle)?;
        let page_box = transform.page_box;

        if page_rectangle.x0 < page_box.x0
            || page_rectangle.y0 < page_box.y0
            || page_rectangle.x1 > page_box.x1
            || page_rectangle.y1 > page_box.y1
        {
            return Err(DhError::InvalidInput(
                "selection rectangle is outside the effective PDF page box".to_owned(),
            ));
        }

        Ok(page_rectangle)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn close(actual: f64, expected: f64) {
        assert!(
            (actual - expected).abs() <= 1e-6,
            "actual={actual}, expected={expected}"
        );
    }

    fn page_transform(rotation_degrees: u16, zoom: f64) -> PageTransform {
        PageTransform {
            page_box: BBox {
                x0: 10.0,
                y0: 20.0,
                x1: 210.0,
                y1: 120.0,
            },
            rotation_degrees,
            zoom,
            device_scale: 1.0,
            // Non-zero viewport origin represents both placement and pan.
            origin_x_px: 125.0,
            origin_y_px: -35.0,
        }
    }

    #[test]
    fn selection_maps_to_the_same_page_box_at_all_zooms_and_rotations() {
        // Independent screen-space oracle for page box (10,20)-(210,120)
        // and page selection (30,40)-(90,80), at unit zoom and zero origin.
        // Each tuple is (relative_x0, relative_y0, relative_x1, relative_y1).
        // These values are deliberately fixed rather than generated by
        // PageTransform so this test does not use the implementation as oracle.
        let expected_unit_screen_boxes = [
            (0, (20.0, 40.0, 80.0, 80.0)),
            (90, (20.0, 20.0, 60.0, 80.0)),
            (180, (120.0, 20.0, 180.0, 60.0)),
            (270, (40.0, 120.0, 80.0, 180.0)),
        ];

        for zoom in [1.0, 2.5, 4.0] {
            for (rotation, (unit_x0, unit_y0, unit_x1, unit_y1)) in expected_unit_screen_boxes {
                let transform = page_transform(rotation, zoom);
                let selection = RegionSelection {
                    page: 0,
                    rectangle: BBox {
                        x0: 125.0 + unit_x0 * zoom,
                        y0: -35.0 + unit_y0 * zoom,
                        x1: 125.0 + unit_x1 * zoom,
                        y1: -35.0 + unit_y1 * zoom,
                    },
                };

                let actual = selection.to_page_user_space(&transform).unwrap();
                close(actual.x0, 30.0);
                close(actual.y0, 40.0);
                close(actual.x1, 90.0);
                close(actual.y1, 80.0);
            }
        }
    }

    #[test]
    fn zero_area_selection_is_rejected() {
        let selection = RegionSelection {
            page: 0,
            rectangle: BBox {
                x0: 100.0,
                y0: 100.0,
                x1: 100.0,
                y1: 140.0,
            },
        };

        let error = selection
            .to_page_user_space(&page_transform(0, 1.0))
            .unwrap_err();
        assert!(format!("{error:?}").contains("positive width and height"));
    }

    #[test]
    fn non_finite_selection_is_rejected() {
        let selection = RegionSelection {
            page: 0,
            rectangle: BBox {
                x0: f64::NAN,
                y0: 100.0,
                x1: 150.0,
                y1: 140.0,
            },
        };

        let error = selection
            .to_page_user_space(&page_transform(0, 1.0))
            .unwrap_err();
        assert!(format!("{error:?}").contains("finite coordinates"));
    }

    #[test]
    fn selection_outside_effective_page_box_is_rejected() {
        let selection = RegionSelection {
            page: 0,
            rectangle: BBox {
                x0: 110.0,
                y0: 65.0,
                x1: 150.0,
                y1: 105.0,
            },
        };

        let error = selection
            .to_page_user_space(&page_transform(0, 1.0))
            .unwrap_err();
        assert!(format!("{error:?}").contains("outside the effective PDF page box"));
    }
}
